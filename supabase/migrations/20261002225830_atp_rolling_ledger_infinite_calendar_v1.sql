-- refresh_world_rankings(p_date date)
CREATE OR REPLACE FUNCTION public.refresh_world_rankings(p_date date DEFAULT CURRENT_DATE)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
 v_date date:=coalesce(p_date,current_date);
 v_updated int:=0;
 v_leader text;
 v_managed bigint;
 v_zero_sync jsonb;
begin
 perform pg_advisory_xact_lock(94832021);
 v_zero_sync:=public.sync_atp_zero_pointers(v_date);
 select managed_player_id into v_managed from public.career_state where id='demo';

 update public.world_ranking_points w
 set active=(
   case when t.category='ATP Finals'
     then date_trunc('week',w.expiry_date::timestamp)::date+7
     else w.expiry_date end
   >=v_date
 )
 from public.tournaments t
 where t.id=w.tournament_id
   and w.active is distinct from (
     case when t.category='ATP Finals'
       then date_trunc('week',w.expiry_date::timestamp)::date+7
       else w.expiry_date end
     >=v_date
   );

 update public.user_ranking_points u
 set active=(
   case when t.category='ATP Finals'
     then date_trunc('week',u.expiry_date::timestamp)::date+7
     else u.expiry_date end
   >=v_date
 )
 from public.tournaments t
 where t.id=u.tournament_id
   and u.active is distinct from (
     case when t.category='ATP Finals'
       then date_trunc('week',u.expiry_date::timestamp)::date+7
       else u.expiry_date end
     >=v_date
   );

 update public.user_ranking_points
 set active=(expiry_date>=v_date)
 where tournament_id is null
   and active is distinct from (expiry_date>=v_date);

 with managed_ids as (
   select v_managed::bigint id where v_managed is not null
   union
   select player_id from public.academy_roster
   where status='active' and player_id is not null
 ),
 metrics as (
   select p.id,s.total_points,s.mandatory_tiebreak_points,s.events_played,s.result_vector,s.counting_events,
          b.rank baseline_rank
   from public.players p
   cross join lateral public.atp_player_ranking_summary(p.id,v_date) s
   left join public.atp_ranking_baseline_2025_12_01 b on b.source_player_id=p.sackmann_id
   where p.career_status='active'
     and coalesce(p.data_source,'') not ilike 'hidden duplicate merged into %'
     and (
       p.ranking_current=true
       or exists(select 1 from managed_ids m where m.id=p.id)
       or exists(select 1 from public.user_ranking_points u where u.player_id=p.id and u.active=true)
     )
 ),
 simulated as (
   select m.*,
     rank() over(
       order by m.total_points desc,m.mandatory_tiebreak_points desc,
                m.events_played asc,m.result_vector desc
     )::int simulated_rank
   from metrics m
 ),
 ranked as (
   select s.*,
     case when v_date=date '2025-12-01' and s.baseline_rank is not null
       then s.baseline_rank else s.simulated_rank end::int new_rank
   from simulated s
 )
 update public.players p
 set points=r.total_points,ranking=r.new_rank,game_world_rank=r.new_rank,ranking_current=true,
     ranking_source=case
       when v_date=date '2025-12-01' and r.baseline_rank is not null
         then 'ATP official 01/12/2025 snapshot · Court Boss event ledger calibrated'
       else 'Court Boss ATP rolling 52w · ATP 2026 counting + official tie-breaks' end,
     ranking_snapshot_date=v_date,
     previous_ranking=coalesce(p.ranking,p.previous_ranking),
     rank_change=case when p.ranking is null then 0 else p.ranking-r.new_rank end
 from ranked r where p.id=r.id;
 get diagnostics v_updated=row_count;

 if v_managed is not null then
   update public.career_state c
   set points=p.points,singles_rank=p.ranking,career_date=v_date,updated_at=now()
   from public.players p where c.id='demo' and p.id=v_managed;
 end if;

 insert into public.ranking_history(player_id,snapshot_date,ranking,points)
 select id,v_date,ranking,points from public.players
 where ranking_current=true and career_status='active'
   and coalesce(data_source,'') not ilike 'hidden duplicate merged into %'
 on conflict do nothing;

 select name into v_leader from public.players
 where ranking_current=true and career_status='active'
 order by ranking nulls last,name limit 1;

 return jsonb_build_object(
   'date',v_date,'updated_players',v_updated,'leader',v_leader,
   'zero_pointer_sync',v_zero_sync,
   'model','ATP 2026 rolling 52w · dynamic slots · max 3 M1000 replacements · official ties'
 );
end;
$function$;

-- ensure_calendar_season(p_year integer)
CREATE OR REPLACE FUNCTION public.ensure_calendar_season(p_year integer)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  v_template_year integer:=2026;
  v_offset integer;
  v_existing integer:=0;
  v_inserted integer:=0;
  v_lowtier integer:=0;
begin
  if p_year<2026 then
    return jsonb_build_object('year',p_year,'inserted',0,'reason','historical_year');
  end if;

  select count(*) into v_existing
  from public.tournaments
  where extract(year from start_date)=p_year and is_active=true;

  if p_year=2026 then
    return jsonb_build_object('year',p_year,'existing',v_existing,'inserted',0,'template',true);
  end if;

  v_offset :=
    date_trunc('week',make_date(p_year,1,4)::timestamp)::date
    - date_trunc('week',make_date(v_template_year,1,4)::timestamp)::date;

  perform pg_advisory_xact_lock(94832027);

  with src as (
    select t.*
    from public.tournaments t
    where extract(year from t.start_date)=v_template_year
      and t.is_active=true
  ),
  missing as (
    select s.*
    from src s
    where not exists(
      select 1
      from public.tournaments x
      where extract(year from x.start_date)=p_year
        and x.is_active=true
        and (
          (s.competition_key is not null and x.competition_key=s.competition_key)
          or
          (s.competition_key is null
           and coalesce(s.history_group,'')<>'' and x.history_group=s.history_group)
          or
          (s.competition_key is null and coalesce(s.history_group,'')=''
           and lower(x.name)=lower(s.name)
           and coalesce(x.category,'')=coalesce(s.category,'')
           and coalesce(x.circuit,'')=coalesce(s.circuit,''))
        )
    )
  )
  insert into public.tournaments(
    name,city,country,surface,level,start_date,end_date,
    singles,doubles,circuit,category,prize_money,draw_size,is_verified,source_url,source_note,
    indoor,venue,is_active,environment,official_season,
    image_url,image_source_url,image_source_label,
    singles_entry_deadline,qualifying_entry_deadline,doubles_entry_deadline,
    singles_draw_size,qualifying_draw_size,doubles_draw_size,winner_points,
    entry_rule_code,entry_rule_note,registration_mode,
    projected_direct_cut,projected_qual_cut,cut_is_projection,
    doubles_onsite_deadline,doubles_entry_method,
    history_group,competition_key,prestige,competition_history_label,
    logo_url,logo_source_url,logo_source_label,
    court_speed,court_speed_source,altitude_m,environment_profile,
    qualifying_start_date,qualifying_end_date,
    prize_currency,prize_money_is_estimate,prize_source_label,prize_source_url,
    singles_prize_by_result,qualifying_prize_by_result,doubles_prize_by_result,
    junior_draw_format,
    singles_withdrawal_deadline,freeze_deadline,performance_bye_slots,performance_bye_source_event,
    main_draw_start_date,main_entry_deadline,withdrawal_deadline,qualifying_signin_date,
    schedule_source_label,
    singles_prize_is_estimate,qualifying_prize_is_estimate,doubles_prize_is_estimate,prize_breakdown_is_estimate,
    prize_format,special_prize_components,prize_total_kind,prize_note,
    late_entry_slots,late_entry_deadline,late_entry_source_label
  )
  select
    n.name,n.city,n.country,n.surface,n.level,
    n.start_date+v_offset,
    case when n.end_date is null then null else n.end_date+v_offset end,
    n.singles,n.doubles,n.circuit,n.category,n.prize_money,n.draw_size,
    false,n.source_url,
    'Court Boss · calendrier auto-généré depuis le patron 2026 · saison '||p_year,
    n.indoor,n.venue,true,n.environment,p_year,
    n.image_url,n.image_source_url,n.image_source_label,
    case when n.singles_entry_deadline is null then null else n.singles_entry_deadline+v_offset end,
    case when n.qualifying_entry_deadline is null then null else n.qualifying_entry_deadline+v_offset end,
    case when n.doubles_entry_deadline is null then null else n.doubles_entry_deadline+v_offset end,
    n.singles_draw_size,n.qualifying_draw_size,n.doubles_draw_size,n.winner_points,
    n.entry_rule_code,n.entry_rule_note,n.registration_mode,
    n.projected_direct_cut,n.projected_qual_cut,true,
    case when n.doubles_onsite_deadline is null then null else n.doubles_onsite_deadline+v_offset end,
    n.doubles_entry_method,
    n.history_group,n.competition_key,n.prestige,n.competition_history_label,
    n.logo_url,n.logo_source_url,n.logo_source_label,
    n.court_speed,n.court_speed_source,n.altitude_m,n.environment_profile,
    case when n.qualifying_start_date is null then null else n.qualifying_start_date+v_offset end,
    case when n.qualifying_end_date is null then null else n.qualifying_end_date+v_offset end,
    n.prize_currency,true,n.prize_source_label,n.prize_source_url,
    n.singles_prize_by_result,n.qualifying_prize_by_result,n.doubles_prize_by_result,
    n.junior_draw_format,
    case when n.singles_withdrawal_deadline is null then null else n.singles_withdrawal_deadline+v_offset end,
    case when n.freeze_deadline is null then null else n.freeze_deadline+v_offset end,
    n.performance_bye_slots,n.performance_bye_source_event,
    case when n.main_draw_start_date is null then null else n.main_draw_start_date+v_offset end,
    case when n.main_entry_deadline is null then null else n.main_entry_deadline+v_offset end,
    case when n.withdrawal_deadline is null then null else n.withdrawal_deadline+v_offset end,
    case when n.qualifying_signin_date is null then null else n.qualifying_signin_date+v_offset end,
    'Court Boss infinite calendar · template 2026',
    true,true,true,true,
    n.prize_format,n.special_prize_components,n.prize_total_kind,n.prize_note,
    n.late_entry_slots,
    case when n.late_entry_deadline is null then null else n.late_entry_deadline+v_offset end,
    n.late_entry_source_label
  from missing n;

  get diagnostics v_inserted=row_count;
  v_lowtier:=public.generate_fictional_tournaments(p_year);

  return jsonb_build_object(
    'year',p_year,
    'template_year',v_template_year,
    'existing_before',v_existing,
    'cloned',v_inserted,
    'fictional_low_tier',v_lowtier,
    'total_after',(
      select count(*) from public.tournaments
      where extract(year from start_date)=p_year and is_active=true
    )
  );
end;
$function$;

-- rollover_season(p_new_year integer)
CREATE OR REPLACE FUNCTION public.rollover_season(p_new_year integer)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  c career_state%rowtype;
  title_count int;
  final_count int;
  prize numeric;
  retired_count int:=0;
  processed_count int:=0;
  newgen_result jsonb;
  ncaa_result jsonb;
  lifecycle_result jsonb;
  calendar_result jsonb;
  next_calendar_result jsonb;
  ranking_result jsonb;
begin
  select * into c from career_state where id='demo';
  if not found then raise exception 'Career not found'; end if;

  calendar_result:=public.ensure_calendar_season(p_new_year);
  next_calendar_result:=public.ensure_calendar_season(p_new_year+1);

  select count(*) filter(where user_round='Champion'),
         count(*) filter(where user_round in ('Champion','F')),
         coalesce(sum(user_prize),0)
    into title_count,final_count,prize
  from tournament_runs
  where extract(year from played_at)=c.season_year;

  insert into season_history(season_year,final_rank,doubles_rank,titles,finals,prize_money,points)
  values(c.season_year,c.singles_rank,c.doubles_rank,title_count,final_count,prize,c.points)
  on conflict(season_year) do update set
    final_rank=excluded.final_rank,doubles_rank=excluded.doubles_rank,titles=excluded.titles,
    finals=excluded.finals,prize_money=excluded.prize_money,points=excluded.points;

  update players
  set age=case
    when birth_date is not null then extract(year from age(make_date(p_new_year,1,5),birth_date))::int
    when age is not null then age+1
    else null end
  where birth_date is not null or age is not null;

  select public.advance_ncaa_lifecycle(p_new_year) into ncaa_result;

  update players
  set current_ability=greatest(30,least(potential,
        current_ability+case
          when age is not null and age<=23 and potential>current_ability and ((id+p_new_year)%4)=0 then 1
          when age is not null and age>=34 and ((id+p_new_year)%3)=0 then -1
          else 0 end)),
      potential=greatest(current_ability,
        potential-case when age is not null and age>=30 and ((id+p_new_year)%5)=0 then 1 else 0 end)
  where ranking_current=true;

  get diagnostics processed_count=row_count;

  select public.refresh_player_career_lifecycle(make_date(p_new_year,1,5))
    into lifecycle_result;
  retired_count:=coalesce((lifecycle_result->>'retired')::int,0);

  select public.generate_newgens(p_new_year) into newgen_result;

  update career_state
  set season_year=p_new_year,age=age+1,week=1,career_date=make_date(p_new_year,1,5),
      fatigue=greatest(5,fatigue-20),fitness=least(100,fitness+10),morale=least(100,morale+5),
      injury_status='Fit',updated_at=now()
  where id='demo';

  update college_career_state
  set eligibility_years=greatest(0,eligibility_years-1),
      academic_progress=greatest(45,academic_progress-5),
      coach_trust=greatest(40,coach_trust-4)
  where player_id is not null
    and status in ('committed','active');

  update sponsor_offers set status='available' where status='declined';

  ranking_result:=public.refresh_world_rankings(make_date(p_new_year,1,5));

  return jsonb_build_object(
    'new_year',p_new_year,
    'retired_players',retired_count,'processed_players',processed_count,
    'newgens',newgen_result,'ncaa_lifecycle',ncaa_result,'career_lifecycle',lifecycle_result,
    'calendar',calendar_result,'next_calendar',next_calendar_result,
    'ranking',ranking_result,
    'previous_titles',title_count,'previous_prize',prize
  );
end;
$function$;


