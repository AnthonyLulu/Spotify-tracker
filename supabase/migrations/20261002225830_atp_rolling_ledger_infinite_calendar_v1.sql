
-- Court Boss ATP rolling ledger + infinite calendar
-- Consolidated repo migration. The live DB was introduced incrementally; this file
-- records the final idempotent state so repo and database stay aligned.

create table if not exists public.atp_defending_points_ledger (
  id bigint generated by default as identity primary key,
  player_id bigint not null references public.players(id) on delete cascade,
  source_season integer not null,
  source_event_key text not null,
  tournament_name text not null,
  source_tournament_id text,
  event_date date not null,
  drop_date date not null,
  rank_category text not null,
  result_code text,
  raw_points integer not null default 0,
  points integer not null default 0,
  counting_at_snapshot boolean not null default false,
  is_estimated boolean not null default true,
  source_label text,
  created_at timestamptz not null default now(),
  unique(player_id,source_season,source_event_key)
);

create index if not exists atp_defending_points_player_drop_idx
  on public.atp_defending_points_ledger(player_id,drop_date);
create index if not exists atp_defending_points_drop_idx
  on public.atp_defending_points_ledger(drop_date);

create table if not exists public.atp_ranking_zero_pointers (
  id bigint generated by default as identity primary key,
  player_id bigint not null references public.players(id) on delete cascade,
  tournament_id bigint not null references public.tournaments(id) on delete cascade,
  earned_date date not null,
  expiry_date date not null,
  rank_category text not null check(rank_category in ('Grand Slam','M1000','ATP500')),
  reason text,
  replacement_eligible boolean not null default false,
  active boolean not null default true,
  source_label text,
  created_at timestamptz not null default now(),
  unique(player_id,tournament_id)
);

create index if not exists atp_zero_pointer_player_date_idx
  on public.atp_ranking_zero_pointers(player_id,earned_date,expiry_date);


-- atp_historical_result_points(p_category text, p_result text, p_competition_key text, p_name text, p_draw integer)
