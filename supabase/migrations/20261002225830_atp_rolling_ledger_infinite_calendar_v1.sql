  when 'W' then 100 when 'F' then 50 when 'SF' then 25 when 'QF' then 14
  when 'R2' then 7 when 'R1' then 0 when 'Q2' then 4 when 'Q1' then 0 else 0 end
 else 0 end);
$function$;

-- atp_historical_rank_category(p_category text, p_competition_key text, p_name text)
CREATE OR REPLACE FUNCTION public.atp_historical_rank_category(p_category text, p_competition_key text DEFAULT NULL::text, p_name text DEFAULT NULL::text)
 RETURNS text
 LANGUAGE sql
 IMMUTABLE
AS $function$
select case
 when p_category='Grand Chelem' then 'Grand Slam'
 when p_category='Masters 1000' then 'M1000'
 when p_category='ATP Finals' then 'Finals'
 when p_category='ATP Tour' and coalesce(p_name,'')='United Cup' then 'United Cup'
 when p_category='ATP Tour' and coalesce(p_name,'')='Laver Cup' then 'Exhibition'
 when p_category='ATP Tour' and (
   coalesce(p_competition_key,'') like 'atp500:%'
