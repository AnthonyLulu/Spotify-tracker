-- record_atp_zero_pointer(p_player_id bigint, p_tournament_id bigint, p_withdrawal_date date, p_reason text)
CREATE OR REPLACE FUNCTION public.record_atp_zero_pointer(p_player_id bigint, p_tournament_id bigint, p_withdrawal_date date DEFAULT CURRENT_DATE, p_reason text DEFAULT 'withdrawal'::text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  t public.tournaments%rowtype;
  v_cat text;
  v_earned date;
begin
  select * into t from public.tournaments where id=p_tournament_id;
  if t.id is null then return jsonb_build_object('recorded',false,'reason','tournament_not_found'); end if;

  v_cat:=case
    when t.category='Grand Chelem' then 'Grand Slam'
    when t.category='Masters 1000' then 'M1000'
    when t.category='ATP 500' then 'ATP500'
    else null end;

  if v_cat is null then
    return jsonb_build_object('recorded',false,'reason','not_zero_pointer_category','category',t.category);
  end if;

  if v_cat='ATP500' then
    return jsonb_build_object(
      'recorded',false,'reason','atp500_commitment_penalty_requires_specific_commitment_rule',
      'category',v_cat
    );
  end if;

  v_earned:=coalesce(t.end_date,t.start_date,p_withdrawal_date);

  insert into public.atp_ranking_zero_pointers(
    player_id,tournament_id,earned_date,expiry_date,rank_category,reason,
    replacement_eligible,active,source_label
  )
  values(
    p_player_id,p_tournament_id,v_earned,v_earned+364,v_cat,p_reason,
    v_cat='M1000',true,'Court Boss · ATP mandatory zero pointer'
  )
  on conflict(player_id,tournament_id) do update set
    earned_date=excluded.earned_date,
    expiry_date=excluded.expiry_date,
    rank_category=excluded.rank_category,
    reason=excluded.reason,
    replacement_eligible=excluded.replacement_eligible,
    active=true,
    source_label=excluded.source_label;

  return jsonb_build_object(
    'recorded',true,'player_id',p_player_id,'tournament_id',p_tournament_id,
    'category',v_cat,'earned_date',v_earned,'expiry_date',v_earned+364,
    'replacement_eligible',v_cat='M1000'
  );
end;
$function$;

-- sync_atp_zero_pointers(p_date date)
CREATE OR REPLACE FUNCTION public.sync_atp_zero_pointers(p_date date DEFAULT CURRENT_DATE)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  v_inserted int:=0;
begin
  insert into public.atp_ranking_zero_pointers(
    player_id,tournament_id,earned_date,expiry_date,rank_category,reason,
    replacement_eligible,active,source_label
  )
  select
    f.player_id,t.id,coalesce(t.end_date,t.start_date),
    coalesce(t.end_date,t.start_date)+364,
    case when t.category='Grand Chelem' then 'Grand Slam' else 'M1000' end,
    coalesce(f.reason,'withdrawal/forfeit'),
    t.category='Masters 1000',
    true,
    'Court Boss · ATP mandatory zero pointer · synced from tournament withdrawal'
  from public.tournament_forfeits f
  join public.tournaments t on t.id=f.tournament_id
  where t.category in ('Grand Chelem','Masters 1000')
    and coalesce(f.withdrawn_on::date,f.created_at::date,t.start_date)<=p_date
    and (
      exists(
        select 1 from public.world_tournament_acceptance_entries a
        where a.tournament_id=t.id and a.player_id=f.player_id
          and coalesce(a.entry_method,'direct') not ilike '%qualif%'
      )
      or exists(
        select 1 from public.entries e
        where e.tournament_id=t.id and e.player_id=f.player_id
          and coalesce(e.entry_method,'direct') not ilike '%qualif%'
      )
    )
  on conflict(player_id,tournament_id) do update set
    active=true,
    reason=excluded.reason,
    source_label=excluded.source_label;

  get diagnostics v_inserted=row_count;

  update public.atp_ranking_zero_pointers
  set active=(expiry_date>=p_date);

  return jsonb_build_object('date',p_date,'synced',v_inserted);
end;
$function$;

-- atp_event_pool(p_player_id bigint, p_date date)
CREATE OR REPLACE FUNCTION public.atp_event_pool(p_player_id bigint, p_date date)
 RETURNS TABLE(event_key text, label text, earned_date date, drop_date date, points integer, rank_category text, source_kind text, estimated boolean)
 LANGUAGE sql
 STABLE
 SET search_path TO 'public'
AS $function$
with managed_primary as (
 select managed_player_id from public.career_state where id='demo'
),
hist as (
 select l.source_event_key as event_key,l.tournament_name as label,l.event_date as earned_date,
        l.drop_date,l.points,l.rank_category,'historical'::text as source_kind,l.is_estimated as estimated
 from public.atp_defending_points_ledger l
 where l.player_id=p_player_id and l.event_date<=p_date and l.drop_date>=p_date
   and (l.points>=0 or l.rank_category='Reconciliation')
),
zeroes as (
 select 'zero:'||z.tournament_id::text as event_key,
        coalesce(t.name,'Tournoi')||' · zero pointer' as label,
        z.earned_date,z.expiry_date as drop_date,0::integer as points,z.rank_category,
        'zero_pointer'::text as source_kind,false as estimated
 from public.atp_ranking_zero_pointers z
 join public.tournaments t on t.id=z.tournament_id
 where z.player_id=p_player_id and z.active=true
   and z.earned_date<=p_date and z.expiry_date>=p_date
),
world as (
 select 'game:'||w.tournament_id::text as event_key,w.label,w.earned_date,
   case when t.category='ATP Finals'
     then date_trunc('week',w.expiry_date::timestamp)::date+7
     else w.expiry_date end as drop_date,
   w.points,
   case when t.category='Grand Chelem' then 'Grand Slam'
    when t.category='Masters 1000' then 'M1000'
    when t.category='ATP Finals' then 'Finals'
    when t.category='United Cup' then 'United Cup'
    when t.category='ATP 500' then 'ATP500'
    when t.category='ATP 250' then 'ATP250'
    when t.circuit='Challenger' then 'Challenger'
    when t.circuit='ITF' then 'ITF'
    else coalesce(t.category,t.circuit,'Other') end as rank_category,
   'world'::text as source_kind,false as estimated
 from public.world_ranking_points w
 left join public.tournaments t on t.id=w.tournament_id
 where w.player_id=p_player_id
   and w.earned_date<=p_date
   and (
     case when t.category='ATP Finals'
       then date_trunc('week',w.expiry_date::timestamp)::date+7
       else w.expiry_date end
   )>=p_date
   and not exists(
     select 1 from public.user_ranking_points u
     where coalesce(u.player_id,(select managed_player_id from managed_primary))=p_player_id
       and u.tournament_id=w.tournament_id
   )
   and not exists(
     select 1 from public.atp_ranking_zero_pointers z
     where z.player_id=p_player_id and z.tournament_id=w.tournament_id and z.active=true
   )
),
usr as (
 select 'game:'||coalesce(u.tournament_id::text,'legacy:'||u.id::text) as event_key,
        u.label,u.earned_date,
   case when t.category='ATP Finals'
     then date_trunc('week',u.expiry_date::timestamp)::date+7
     else u.expiry_date end as drop_date,
   u.points,
   case when t.category='Grand Chelem' then 'Grand Slam'
    when t.category='Masters 1000' then 'M1000'
    when t.category='ATP Finals' then 'Finals'
    when t.category='United Cup' then 'United Cup'
    when t.category='ATP 500' then 'ATP500'
    when t.category='ATP 250' then 'ATP250'
    when t.circuit='Challenger' then 'Challenger'
    when t.circuit='ITF' then 'ITF'
    else case when u.tournament_id is null then 'Legacy' else coalesce(t.category,t.circuit,'Other') end end as rank_category,
   'managed'::text as source_kind,(u.tournament_id is null) as estimated
 from public.user_ranking_points u
 left join public.tournaments t on t.id=u.tournament_id
 where coalesce(u.player_id,(select managed_player_id from managed_primary))=p_player_id
   and u.earned_date<=p_date
   and (
     case when t.category='ATP Finals'
       then date_trunc('week',u.expiry_date::timestamp)::date+7
       else u.expiry_date end
   )>=p_date
   and (
     u.tournament_id is not null
     or not exists(select 1 from public.atp_defending_points_ledger z where z.player_id=p_player_id)
   )
   and not exists(
     select 1 from public.atp_ranking_zero_pointers z
     where z.player_id=p_player_id and z.tournament_id=u.tournament_id and z.active=true
   )
),
unioned as (
 select * from hist union all select * from zeroes union all select * from world union all select * from usr
),
dedup as (
 select distinct on(event_key) event_key,label,earned_date,drop_date,points,rank_category,source_kind,estimated
 from unioned
 order by event_key,
   case source_kind when 'managed' then 0 when 'zero_pointer' then 1 when 'world' then 2 else 3 end
)
select * from dedup;
$function$;

-- atp_player_breakdown(p_player_id bigint, p_date date)
CREATE OR REPLACE FUNCTION public.atp_player_breakdown(p_player_id bigint, p_date date)
 RETURNS TABLE(event_key text, label text, earned_date date, drop_date date, points integer, rank_category text, counting boolean, counting_reason text, replaced_m1000 boolean, replacement_event boolean, source_kind text, estimated boolean)
 LANGUAGE sql
 STABLE
 SET search_path TO 'public'
AS $function$
with pool as (select * from public.atp_event_pool(p_player_id,p_date)),
counts as (
 select
   count(*) filter(where rank_category in ('Grand Slam','M1000'))::int mandatory_events,
   count(*) filter(where rank_category not in ('Grand Slam','M1000','Finals','Reconciliation'))::int optional_events
 from pool
),
slot_info as (
 select mandatory_events,optional_events,
        greatest(0,18-mandatory_events)::int optional_slots,
        greatest(0,least(3,optional_events-greatest(0,18-mandatory_events)))::int replacement_capacity
 from counts
),
m_candidates as (
 select p.*,row_number() over(order by p.points asc,p.earned_date asc,p.event_key) rn
 from pool p
 where p.rank_category='M1000'
   and exists(
     select 1 from pool o
     where o.rank_category in ('ATP500','ATP250')
       and o.earned_date>p.earned_date and o.points>p.points
   )
),
replace_m as (
 select m.*
 from m_candidates m cross join slot_info s
 where m.rn<=s.replacement_capacity
),
replacement_candidates as (
 select p.*,row_number() over(order by p.points desc,p.earned_date desc,p.event_key) rn
 from pool p
 where p.rank_category in ('ATP500','ATP250')
   and exists(
     select 1 from replace_m m
     where p.earned_date>m.earned_date and p.points>m.points
   )
),
replace_o as (
 select * from replacement_candidates where rn<=(select count(*) from replace_m)
),
optional_ranked as (
 select p.event_key,row_number() over(order by p.points desc,p.earned_date desc,p.event_key) rn
 from pool p
 where p.rank_category not in ('Grand Slam','M1000','Finals','Reconciliation')
   and not exists(select 1 from replace_o r where r.event_key=p.event_key)
),
classified as (
 select p.*,
   exists(select 1 from replace_m m where m.event_key=p.event_key) replaced_m1000,
   exists(select 1 from replace_o r where r.event_key=p.event_key) replacement_event,
   case
    when p.rank_category='Reconciliation' then true
    when p.rank_category='Grand Slam' then true
    when p.rank_category='M1000' and not exists(select 1 from replace_m m where m.event_key=p.event_key) then true
    when p.rank_category='Finals' then true
    when exists(select 1 from replace_o r where r.event_key=p.event_key) then true
    when exists(
      select 1 from optional_ranked o cross join slot_info s
      where o.event_key=p.event_key and o.rn<=s.optional_slots
    ) then true
    else false end counting
 from pool p
)
select c.event_key,c.label,c.earned_date,c.drop_date,c.points,c.rank_category,c.counting,
 case
  when c.rank_category='Reconciliation' then 'Réconciliation historique avec le total ATP officiel du 01/12/2025'
  when c.rank_category='Grand Slam' then 'Grand Chelem obligatoire'
  when c.rank_category='M1000' and c.replaced_m1000 then 'M1000 remplacé par meilleur ATP 500/250 ultérieur'
  when c.rank_category='M1000' then 'Masters 1000 obligatoire'
  when c.rank_category='Finals' then 'ATP Finals en plus du socle'
  when c.replacement_event then 'Remplacement M1000 (max 3 sur 52 semaines)'
  when c.counting then 'Meilleur résultat optionnel'
  else 'Non comptabilisé actuellement' end,
 c.replaced_m1000,c.replacement_event,c.source_kind,c.estimated
from classified c
order by c.counting desc,c.points desc,c.earned_date desc,c.event_key;
$function$;

-- atp_player_ranking_summary(p_player_id bigint, p_date date)
CREATE OR REPLACE FUNCTION public.atp_player_ranking_summary(p_player_id bigint, p_date date)
 RETURNS TABLE(total_points integer, mandatory_tiebreak_points integer, events_played integer, result_vector integer[], counting_events integer)
 LANGUAGE sql
 STABLE
 SET search_path TO 'public'
AS $function$
with b as (select * from public.atp_player_breakdown(p_player_id,p_date)),
pool as (select * from public.atp_event_pool(p_player_id,p_date))
select
 coalesce(sum(points) filter(where counting),0)::int,
 coalesce(sum(points) filter(where rank_category in ('Grand Slam','M1000','Finals')),0)::int,
 (select count(*)::int from pool where rank_category<>'Reconciliation'),
 coalesce(array_agg(points order by points desc,earned_date desc)
   filter(where counting and rank_category<>'Reconciliation'),array[]::integer[]),
 count(*) filter(where counting and rank_category<>'Reconciliation')::int
from b;
$function$;

-- atp_points_to_defend(p_player_id bigint, p_date date, p_weeks integer)
CREATE OR REPLACE FUNCTION public.atp_points_to_defend(p_player_id bigint, p_date date, p_weeks integer DEFAULT 52)
 RETURNS TABLE(week_start date, week_end date, points_to_defend integer, events jsonb)
 LANGUAGE sql
 STABLE
 SET search_path TO 'public'
AS $function$
with weeks as (
 select (date_trunc('week',p_date::timestamp)::date+(g*7))::date week_start,
        (date_trunc('week',p_date::timestamp)::date+(g*7+6))::date week_end
 from generate_series(0,greatest(0,least(104,p_weeks))-1) g
),
b as (
 select * from public.atp_player_breakdown(p_player_id,p_date) where counting=true
)
select w.week_start,w.week_end,coalesce(sum(b.points),0)::int,
 coalesce(jsonb_agg(jsonb_build_object(
   'event_key',b.event_key,'label',b.label,'drop_date',b.drop_date,'points',b.points,
   'category',b.rank_category,'reason',b.counting_reason,'estimated',b.estimated
 ) order by b.drop_date,
   case when b.rank_category='Reconciliation' then 1 else 0 end,
   b.points desc) filter(where b.event_key is not null),'[]'::jsonb)
from weeks w
left join b on b.drop_date between w.week_start and w.week_end
group by w.week_start,w.week_end order by w.week_start;
$function$;


-- Rebuild the 01/12/2025 defending-points portfolio from historical results.
delete from public.atp_defending_points_ledger where source_season=2025;

with history_source as (
 select h.player_id,h.tournament_id,h.tournament_name,h.tournament_date,h.category,h.result_code,
        c.competition_key,c.draw_size,
        public.atp_historical_rank_category(h.category,c.competition_key,h.tournament_name) rank_category,
        public.atp_historical_result_points(h.category,h.result_code,c.competition_key,h.tournament_name,c.draw_size) raw_points
 from public.player_tournament_history h
 left join lateral (
   select ch.competition_key,ch.draw_size
   from public.competition_history ch
   where ch.season=2025 and ch.event_type='singles'
     and lower(regexp_replace(ch.tournament_name,'[^a-z0-9]+','','g'))=
         lower(regexp_replace(h.tournament_name,'[^a-z0-9]+','','g'))
   order by ch.id limit 1
 ) c on true
 where h.season=2025 and h.event_type='singles'
   and h.tournament_date between date '2024-12-02' and date '2025-12-01'
)
insert into public.atp_defending_points_ledger(
 player_id,source_season,source_event_key,tournament_name,source_tournament_id,event_date,drop_date,
 rank_category,result_code,raw_points,points,counting_at_snapshot,is_estimated,source_label
)
select player_id,2025,'hist:'||tournament_id,tournament_name,tournament_id,tournament_date,
       case when rank_category='Finals'
         then date_trunc('week',(tournament_date+364)::timestamp)::date+7
         else tournament_date+364 end,
       rank_category,result_code,raw_points,raw_points,false,
       (rank_category in ('Challenger','United Cup')),
       case when rank_category in ('Challenger','United Cup')
         then 'Court Boss · résultat 2025 réel, niveau/points partiellement estimés'
         else 'Court Boss · résultat 2025 + barème ATP 2026' end
from history_source
where rank_category<>'Exhibition'
on conflict(player_id,source_season,source_event_key) do update set
  tournament_name=excluded.tournament_name,
  event_date=excluded.event_date,
  drop_date=excluded.drop_date,
  rank_category=excluded.rank_category,
  result_code=excluded.result_code,
  raw_points=excluded.raw_points,
  points=excluded.points,
  is_estimated=excluded.is_estimated,
  source_label=excluded.source_label;

delete from public.atp_defending_points_ledger
where source_season=2025 and rank_category='Reconciliation';

with official as (
 select p.id player_id,b.points official_points
 from public.atp_ranking_baseline_2025_12_01 b
 join public.players p on p.sackmann_id=b.source_player_id
),
calc as (
 select o.player_id,o.official_points,coalesce(s.total_points,0) total_points,
        o.official_points-coalesce(s.total_points,0) delta
 from official o
 left join lateral public.atp_player_ranking_summary(o.player_id,date '2025-12-01') s on true
)
insert into public.atp_defending_points_ledger(
 player_id,source_season,source_event_key,tournament_name,source_tournament_id,event_date,drop_date,
 rank_category,result_code,raw_points,points,counting_at_snapshot,is_estimated,source_label
)
select c.player_id,2025,'hist:ranking-reconciliation','Réconciliation classement ATP 01/12/2025',null,
       date '2025-12-01',date '2026-11-30','Reconciliation',null,0,c.delta,true,true,
       'Court Boss · écart résiduel entre historique détaillé et total ATP officiel du 01/12/2025'
from calc c where c.delta<>0
on conflict(player_id,source_season,source_event_key) do update set
  points=excluded.points,drop_date=excluded.drop_date,source_label=excluded.source_label;

update public.atp_defending_points_ledger l
set counting_at_snapshot=b.counting
from (
 select p.id player_id,x.event_key,x.counting
 from public.players p
 cross join lateral public.atp_player_breakdown(p.id,date '2025-12-01') x
 where p.ranking_current=true
) b
where l.player_id=b.player_id and l.source_event_key=b.event_key;


