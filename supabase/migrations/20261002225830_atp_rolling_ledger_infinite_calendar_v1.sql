 RETURNS integer
 LANGUAGE sql
 IMMUTABLE
 SET search_path TO 'public'
AS $function$
select greatest(0,case
 when p_category='Grand Chelem' then case upper(coalesce(p_result,''))
  when 'W' then 2000 when 'F' then 1300 when 'SF' then 800 when 'QF' then 400
  when 'R4' then 200 when 'R3' then 100 when 'R2' then 50 when 'R1' then 10
  when 'Q3' then 16 when 'Q2' then 8 else 0 end
 when p_category='Masters 1000' then case upper(coalesce(p_result,''))
  when 'W' then 1000 when 'F' then 650 when 'SF' then 400 when 'QF' then 200
  when 'R4' then 100
  when 'R3' then case when coalesce(p_draw,96)>56 then 50 else 100 end
  when 'R2' then case when coalesce(p_draw,96)>56 then 30 else 50 end
  when 'R1' then 10
  when 'Q3' then 16
  when 'Q2' then case when coalesce(p_draw,96)>56 then 10 else 16 end
  else 0 end
 when p_category='ATP Finals' then case upper(coalesce(p_result,''))
  when 'W' then 1500 when 'F' then 1000 when 'SF' then 600 when 'RR' then 200 else 0 end
 when p_category='ATP Tour' and coalesce(p_name,'')='Laver Cup' then 0
 when p_category='ATP Tour' and coalesce(p_name,'')='United Cup' then case upper(coalesce(p_result,''))
  when 'W' then 500 when 'F' then 350 when 'SF' then 250 when 'QF' then 150 when 'RR' then 75 else 0 end
 when p_category='ATP Tour' and (
   coalesce(p_competition_key,'') like 'atp500:%'
   or lower(coalesce(p_name,'')) in (
     'dallas','rotterdam','doha','rio de janeiro','dubai','acapulco',
     'barcelona','munich','hamburg','queen''s club','halle','washington',
     'tokyo','beijing','vienna','basel'
   )
 ) then case upper(coalesce(p_result,''))
  when 'W' then 500 when 'F' then 330 when 'SF' then 200 when 'QF' then 100
  when 'R3' then 50
  when 'R2' then case when coalesce(p_draw,32)>32 then 25 else 50 end
  when 'R1' then 0
  when 'Q2' then case when coalesce(p_draw,32)>32 then 8 else 13 end
  else 0 end
