create or replace function public.court_boss_award_world_news_trigger()
returns trigger
language plpgsql
security invoker
set search_path to ''
as $function$
declare v_date date; v_count bigint:=0;
begin
  if new.award_rank<>1 or new.season<=2025 then return new; end if;
  v_date:=make_date(new.season,12,31);
  if new.award_code='player_of_year' then
    perform public.court_boss_publish_world_story(
      'player_of_year:'||new.season||':'||new.player_id,v_date,new.player_id,'award',
      new.player_name||' est sacré joueur de l’année '||new.season||'.',
      jsonb_build_object('award_code',new.award_code,'season',new.season,'score',new.score)
    );
    perform public.court_boss_publish_legacy_rank_story(new.player_id,v_date,'son titre de joueur de l’année '||new.season);

    select coalesce((select count(*) from public.court_boss_year_end_no1_reference y where lower(y.player_name)=lower(new.player_name)),0)
      +coalesce((select count(*) from public.court_boss_player_awards a
        where a.player_id=new.player_id and a.award_code='player_of_year' and a.award_rank=1 and a.season>2025 and a.season<=new.season),0)
    into v_count;

    if v_count>=8 and not exists(
      select 1 from public.record_occurrences where record_code='player_of_year_awards'
        and player_id=new.player_id and coalesce(value,0)>=v_count
    ) then
      insert into public.record_occurrences(record_code,player_id,player_name,country,season,achieved_on,value,label,source_type,source_label,source_url,metadata)
      values('player_of_year_awards',new.player_id,new.player_name,new.country,new.season,v_date,v_count,
        v_count||' awards joueur de l’année','career','Court Boss · awards v1','',jsonb_build_object('season',new.season));
    end if;
  end if;
  return new;
end;
$function$;

