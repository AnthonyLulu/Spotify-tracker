create or replace function public.court_boss_publish_daily_legacy_rank_moves(p_date date)
returns jsonb
language plpgsql
security invoker
set search_path to ''
as $function$
declare
  r record; v_published int:=0; v_threshold int; v_displaced text; v_body text;
begin
  if p_date<=date '2025-12-01' then return jsonb_build_object('date',p_date,'published',0); end if;
  for r in
    with active as (
      select distinct player_id from public.court_boss_match_stat_lines where match_date=p_date
    ),
    before_rank as (
      select l.* from public.court_boss_legacy_leaderboard(p_date-1) l join active a on a.player_id=l.player_id
    ),
    after_rank as (
      select l.* from public.court_boss_legacy_leaderboard(p_date) l join active a on a.player_id=l.player_id
    )
    select a.player_id,a.player_name,a.all_time_rank after_rank,a.legacy_score,b.all_time_rank before_rank
    from after_rank a left join before_rank b on b.player_id=a.player_id
    where (a.all_time_rank=1 and coalesce(b.all_time_rank,999999)>1)
      or (a.all_time_rank<=3 and coalesce(b.all_time_rank,999999)>3)
      or (a.all_time_rank<=5 and coalesce(b.all_time_rank,999999)>5)
      or (a.all_time_rank<=10 and coalesce(b.all_time_rank,999999)>10)
      or (a.all_time_rank<=20 and coalesce(b.all_time_rank,999999)>20)
    order by a.all_time_rank
  loop
    v_threshold:=case
      when r.after_rank=1 and coalesce(r.before_rank,999999)>1 then 1
      when r.after_rank<=3 and coalesce(r.before_rank,999999)>3 then 3
      when r.after_rank<=5 and coalesce(r.before_rank,999999)>5 then 5
      when r.after_rank<=10 and coalesce(r.before_rank,999999)>10 then 10
      else 20 end;

    select player_name into v_displaced
    from public.court_boss_legacy_leaderboard(p_date-1)
    where all_time_rank=r.after_rank and player_id<>r.player_id
    order by legacy_score desc limit 1;

    v_body:=case when v_threshold=1
      then r.player_name||' prend la tête du classement Legacy all-time'
      else r.player_name||' entre dans le Top '||v_threshold||' du classement Legacy all-time' end
      ||case when v_displaced is not null then ' en dépassant '||v_displaced else '' end
      ||' grâce à sa progression sur le circuit.';

    if public.court_boss_publish_world_story(
      'legacy_top_'||v_threshold||':'||r.player_id,p_date,r.player_id,'legacy_rank',v_body,
      jsonb_build_object('before_rank',r.before_rank,'after_rank',r.after_rank,'threshold',v_threshold,
        'displaced_player',v_displaced,'legacy_score',r.legacy_score)
    ) then v_published:=v_published+1; end if;
  end loop;
  return jsonb_build_object('date',p_date,'published',v_published,'model','CB-LEGACY-NEWS-v1');
end;
$function$;

create or replace function public.advance_career_day_v26(
  p_today_plan jsonb default '{}'::jsonb,
  p_difficulty text default 'normal'::text,
  p_expected_from_date date default null::date
)
returns jsonb
language plpgsql
security definer
set search_path to ''
as $function$
declare
  v_current public.career_state%rowtype;
  v_existing jsonb;
  v_result jsonb;
  v_result_date date;
  v_story_date date;
  v_legacy_news jsonb:=jsonb_build_object('published',0);
  v_week int;
begin
  perform pg_advisory_xact_lock(2200261201);
  select * into v_current from public.career_state where id='demo' for update;
  if not found then return jsonb_build_object('ok',false,'reason','career_missing','model','CB-DAILY-CLOCK-v26'); end if;

  if p_expected_from_date is not null then
    select cel.payload->'result' into v_existing
    from public.career_event_log cel
    where cel.event_type='daily_tick_commit_v25'
      and coalesce(cel.payload->>'from_date','')=p_expected_from_date::text
    order by cel.id desc limit 1;
    if v_existing is not null then
      return v_existing||jsonb_build_object('ok',true,'already_applied',true,'idempotent_replay',true,
        'expected_from_date',p_expected_from_date,'model','CB-DAILY-CLOCK-v26');
    end if;
    if coalesce(v_current.career_date,date '2025-12-01')<>p_expected_from_date then
      return jsonb_build_object('ok',false,'reason','stale_day_request','retryable',false,
        'expected_from_date',p_expected_from_date,'current_date',v_current.career_date,'model','CB-DAILY-CLOCK-v26');
    end if;
  end if;

  v_result:=public.advance_career_day_v22(coalesce(p_today_plan,'{}'::jsonb),coalesce(p_difficulty,'normal'));

  if coalesce((v_result->>'ok')::boolean,false)=true and nullif(v_result->>'date','') is not null then
    v_result_date:=(v_result->>'date')::date;
    v_week:=coalesce((v_result->>'week')::int,1);
    v_story_date:=coalesce(p_expected_from_date,nullif(v_result->>'from_date','')::date,v_result_date-1);
    v_legacy_news:=public.court_boss_publish_daily_legacy_rank_moves(v_story_date);
    v_result:=v_result||jsonb_build_object('legacy_news',v_legacy_news);

    insert into public.career_event_log(event_date,week,system,event_type,entity_type,entity_id,summary,payload)
    values(v_result_date,v_week,'clock','daily_tick_commit_v25','career',null,
      'Commit journée idempotent '||coalesce(p_expected_from_date::text,(v_result->>'from_date'),'')||' → '||v_result_date::text,
      jsonb_build_object('from_date',coalesce(p_expected_from_date::text,v_result->>'from_date'),
        'to_date',v_result_date,'result',v_result));
  end if;

  return coalesce(v_result,'{}'::jsonb)||jsonb_build_object(
    'expected_from_date',p_expected_from_date,'model','CB-DAILY-CLOCK-v26'
  );
end;
$function$;

