-- Court Boss Legacy world news v10
-- World-record breakthroughs, Slam milestones, Player of the Year stories,
-- all-time Legacy threshold crossings, and idempotent news publication.

create table if not exists public.court_boss_world_story_log (
  id bigint generated by default as identity primary key,
  story_key text not null unique,
  event_date date not null,
  player_id bigint references public.players(id) on delete set null,
  story_type text not null,
  body text not null,
  metadata jsonb not null default '{}'::jsonb,
  news_item_id bigint,
  created_at timestamptz not null default now()
);

alter table public.court_boss_world_story_log enable row level security;
revoke all on public.court_boss_world_story_log from public,anon,authenticated;
grant select,insert,update,delete on public.court_boss_world_story_log to service_role;

create index if not exists idx_cb_world_story_date
  on public.court_boss_world_story_log(event_date desc,story_type);
create index if not exists idx_cb_world_story_player
  on public.court_boss_world_story_log(player_id,event_date desc);

create or replace function public.court_boss_legacy_leaderboard(p_date date)
returns table(
  all_time_rank bigint,
  player_id bigint,
  player_name text,
  country text,
  legacy_score bigint,
  titles bigint,
  grand_slams bigint,
  masters bigint,
  tour_finals bigint,
  wins bigint,
  losses bigint,
  weeks_no1 bigint,
  player_of_year bigint
)
language sql
stable
security invoker
set search_path to ''
as $function$
with future_titles as (
  select pt.player_id,
    count(*)::bigint titles,
    count(*) filter(where public.cb_record_event_key(pt.tournament_name) in ('australian_open','roland_garros','wimbledon','us_open'))::bigint slams,
    count(*) filter(where coalesce(pt.level,'') ilike '%1000%')::bigint masters,
    count(*) filter(where coalesce(pt.level,'') ilike '%ATP Finals%'
      or lower(coalesce(pt.tournament_name,'')) like '%tour finals%'
      or lower(coalesce(pt.tournament_name,'')) like '%atp finals%'
      or lower(coalesce(pt.tournament_name,'')) like '%masters cup%')::bigint finals
  from public.player_titles pt
  where pt.event_type='singles'
    and pt.title_date>date '2025-12-01'
    and pt.title_date<=coalesce(p_date,date '2025-12-01')
  group by pt.player_id
),
future_stats as (
  select s.player_id,
    count(*) filter(where s.won)::bigint wins,
    count(*) filter(where not s.won)::bigint losses
  from public.court_boss_match_stat_lines s
  where s.match_date>date '2025-12-01'
    and s.match_date<=coalesce(p_date,date '2025-12-01')
  group by s.player_id
),
future_no1 as (
  select rh.player_id,count(*)::bigint weeks_no1
  from public.ranking_history rh
  where rh.snapshot_date>date '2025-12-01'
    and rh.snapshot_date<=coalesce(p_date,date '2025-12-01')
    and rh.ranking=1
  group by rh.player_id
),
future_awards as (
  select a.player_id,
    count(*) filter(where a.award_code='player_of_year' and a.award_rank=1)::bigint poy
  from public.court_boss_player_awards a
  where a.season>2025
    and a.season<=extract(year from coalesce(p_date,date '2025-12-01'))::int
  group by a.player_id
),
historical_poy as (
  select p.id player_id,count(y.season)::bigint poy
  from public.players p
  join public.court_boss_year_end_no1_reference y on lower(y.player_name)=lower(p.name)
  where y.season<=least(2025,extract(year from coalesce(p_date,date '2025-12-01'))::int)
    and coalesce(p.data_source,'') not ilike '%hidden duplicate merged into%'
  group by p.id
),
scored as (
  select p.id,p.name,p.country,
    (coalesce(h.titles,0)+coalesce(ft.titles,0))::bigint titles,
    (coalesce(h.grand_slams,0)+coalesce(ft.slams,0))::bigint slams,
    (coalesce(h.masters,0)+coalesce(ft.masters,0))::bigint masters,
    (coalesce(h.tour_finals,0)+coalesce(ft.finals,0))::bigint finals,
    (greatest(coalesce(h.wins,0),coalesce(pcs.wins,0))+coalesce(fs.wins,0))::bigint wins,
    (greatest(coalesce(h.losses,0),coalesce(pcs.losses,0))+coalesce(fs.losses,0))::bigint losses,
    (coalesce(p.weeks_at_no1,0)+coalesce(fn.weeks_no1,0))::bigint weeks_no1,
    (coalesce(hp.poy,0)+coalesce(fa.poy,0))::bigint poy,
    (
      (coalesce(h.grand_slams,0)+coalesce(ft.slams,0))*10000
      +(coalesce(h.tour_finals,0)+coalesce(ft.finals,0))*2200
      +(coalesce(h.masters,0)+coalesce(ft.masters,0))*1200
      +greatest(
        (coalesce(h.titles,0)+coalesce(ft.titles,0))
        -(coalesce(h.grand_slams,0)+coalesce(ft.slams,0))
        -(coalesce(h.masters,0)+coalesce(ft.masters,0))
        -(coalesce(h.tour_finals,0)+coalesce(ft.finals,0)),0
      )*180
      +(greatest(coalesce(h.wins,0),coalesce(pcs.wins,0))+coalesce(fs.wins,0))*2
      +(coalesce(p.weeks_at_no1,0)+coalesce(fn.weeks_no1,0))*8
      +(coalesce(hp.poy,0)+coalesce(fa.poy,0))*1500
    )::bigint legacy_score
  from public.players p
  left join public.history_player_scores h on h.id=p.id
  left join public.player_career_stats pcs on pcs.player_id=p.id
  left join future_titles ft on ft.player_id=p.id
  left join future_stats fs on fs.player_id=p.id
  left join future_no1 fn on fn.player_id=p.id
  left join future_awards fa on fa.player_id=p.id
  left join historical_poy hp on hp.player_id=p.id
  where coalesce(p.data_source,'') not ilike '%hidden duplicate merged into%'
),
eligible as (select * from scored where legacy_score>0)
select
  rank() over(order by legacy_score desc,slams desc,titles desc,wins desc,id)::bigint,
  id::bigint,name,country,legacy_score,titles,slams,masters,finals,wins,losses,weeks_no1,poy
from eligible
order by legacy_score desc,slams desc,titles desc,wins desc,id;
$function$;

create or replace function public.court_boss_all_time_snapshot(p_player_id bigint,p_date date)
returns jsonb
language sql
stable
security invoker
set search_path to ''
as $function$
select coalesce(
  (
    select jsonb_build_object(
      'rank',l.all_time_rank,
      'pool',(select count(*) from public.court_boss_legacy_leaderboard(p_date)),
      'score',l.legacy_score,'titles',l.titles,'grand_slams',l.grand_slams,
      'masters',l.masters,'tour_finals',l.tour_finals,'wins',l.wins,'losses',l.losses,
      'weeks_no1',l.weeks_no1,'player_of_year',l.player_of_year,
      'tier',case
        when l.all_time_rank<=3 then 'GOAT tier'
        when l.all_time_rank<=10 then 'Panthéon'
        when l.all_time_rank<=50 then 'Légende'
        when l.all_time_rank<=200 then 'Élite historique'
        else 'Référence historique'
      end
    )
    from public.court_boss_legacy_leaderboard(p_date) l
    where l.player_id=p_player_id
  ),
  jsonb_build_object(
    'rank',null,'pool',(select count(*) from public.court_boss_legacy_leaderboard(p_date)),
    'score',0,'titles',0,'grand_slams',0,'masters',0,'tour_finals',0,
    'wins',0,'losses',0,'weeks_no1',0,'player_of_year',0,'tier','En construction'
  )
);
$function$;

create or replace function public.court_boss_publish_world_story(
  p_story_key text,p_event_date date,p_player_id bigint,p_story_type text,p_body text,
  p_metadata jsonb default '{}'::jsonb
)
returns boolean
language plpgsql
security invoker
set search_path to ''
as $function$
declare v_log_id bigint; v_news_id bigint;
begin
  if coalesce(trim(p_story_key),'')='' or coalesce(trim(p_body),'')='' then return false; end if;
  insert into public.court_boss_world_story_log(story_key,event_date,player_id,story_type,body,metadata)
  values(p_story_key,coalesce(p_event_date,current_date),p_player_id,
    coalesce(nullif(p_story_type,''),'legacy'),p_body,coalesce(p_metadata,'{}'::jsonb))
  on conflict(story_key) do nothing returning id into v_log_id;
  if v_log_id is null then return false; end if;
  insert into public.news_items(body) values(p_body) returning id into v_news_id;
  update public.court_boss_world_story_log set news_item_id=v_news_id where id=v_log_id;
  return true;
end;
$function$;

create or replace function public.court_boss_publish_record_occurrence_news(p_occurrence_id bigint)
returns boolean
language plpgsql
security invoker
set search_path to ''
as $function$
declare
  r public.record_occurrences%rowtype;
  c public.record_catalog%rowtype;
  v_body text;
  v_key text;
begin
  select * into r from public.record_occurrences where id=p_occurrence_id;
  if r.id is null or r.achieved_on<=date '2025-12-01' or coalesce(r.source_type,'')<>'career' then return false; end if;
  select * into c from public.record_catalog where code=r.record_code;
  if c.code is null then return false; end if;

  if c.record_type in ('numeric','dynamic') and c.baseline_value is not null and r.value is not null and r.value>=c.baseline_value then
    if r.value>c.baseline_value then
      v_body:='Nouveau record mondial : '||r.player_name||' efface '||coalesce(c.baseline_holder,'l’ancienne référence')
        ||' avec '||trim(to_char(r.value,'FM999999990.##'))||case when c.unit is not null then ' '||c.unit else '' end
        ||' · '||c.name||'.';
      v_key:='world_record:'||r.record_code||':'||r.player_id||':'||trim(to_char(r.value,'FM999999990.##'));
    else
      v_body:=r.player_name||' égale le record de '||coalesce(c.baseline_holder,'référence')
        ||' : '||trim(to_char(r.value,'FM999999990.##'))||case when c.unit is not null then ' '||c.unit else '' end
        ||' · '||c.name||'.';
      v_key:='record_equal:'||r.record_code||':'||r.player_id||':'||trim(to_char(r.value,'FM999999990.##'));
    end if;
  elsif c.record_type in ('achievement','challenge') and c.rarity in ('mythic','legendary') then
    v_body:=case when c.rarity='mythic'
      then r.player_name||' signe un exploit historique : '
      else r.player_name||' ajoute un exploit majeur à sa carrière : ' end
      ||c.name||case when coalesce(r.label,'')<>'' then ' · '||r.label else '' end||'.';
    v_key:='achievement:'||r.record_code||':'||r.player_id||':'||coalesce(r.season,-1);
  else
    return false;
  end if;

  return public.court_boss_publish_world_story(
    v_key,r.achieved_on,r.player_id,
    case when c.record_type in ('numeric','dynamic') then 'world_record' else 'achievement' end,
    v_body,jsonb_build_object(
      'record_occurrence_id',r.id,'record_code',r.record_code,'record_name',c.name,
      'rarity',c.rarity,'value',r.value,'baseline_value',c.baseline_value,'baseline_holder',c.baseline_holder
    )
  );
end;
$function$;

