create or replace function public.court_boss_publish_legacy_rank_story(
  p_player_id bigint,p_event_date date,p_reason text default null
)
returns boolean
language plpgsql
security invoker
set search_path to ''
as $function$
declare
  v_before record; v_after record; v_displaced text; v_body text; v_key text; v_threshold int;
begin
  if p_event_date<=date '2025-12-01' then return false; end if;
  select * into v_before from public.court_boss_legacy_leaderboard(p_event_date-1) where player_id=p_player_id;
  select * into v_after from public.court_boss_legacy_leaderboard(p_event_date) where player_id=p_player_id;
  if v_after.player_id is null or v_after.all_time_rank is null then return false; end if;

  v_threshold:=case
    when v_after.all_time_rank=1 and coalesce(v_before.all_time_rank,999999)>1 then 1
    when v_after.all_time_rank<=3 and coalesce(v_before.all_time_rank,999999)>3 then 3
    when v_after.all_time_rank<=5 and coalesce(v_before.all_time_rank,999999)>5 then 5
    when v_after.all_time_rank<=10 and coalesce(v_before.all_time_rank,999999)>10 then 10
    when v_after.all_time_rank<=20 and coalesce(v_before.all_time_rank,999999)>20 then 20
    else null end;
  if v_threshold is null then return false; end if;

  select player_name into v_displaced
  from public.court_boss_legacy_leaderboard(p_event_date-1)
  where all_time_rank=v_after.all_time_rank and player_id<>p_player_id
  order by legacy_score desc limit 1;

  v_body:=case when v_threshold=1
    then v_after.player_name||' prend la tête du classement Legacy all-time'
    else v_after.player_name||' entre dans le Top '||v_threshold||' du classement Legacy all-time' end
    ||case when v_displaced is not null then ' en dépassant '||v_displaced else '' end
    ||case when coalesce(trim(p_reason),'')<>'' then ' après '||trim(p_reason) else '' end||'.';
  v_key:='legacy_top_'||v_threshold||':'||p_player_id;

  return public.court_boss_publish_world_story(
    v_key,p_event_date,p_player_id,'legacy_rank',v_body,
    jsonb_build_object('before_rank',v_before.all_time_rank,'after_rank',v_after.all_time_rank,
      'threshold',v_threshold,'displaced_player',v_displaced,'reason',p_reason,'legacy_score',v_after.legacy_score)
  );
end;
$function$;

create or replace function public.court_boss_publish_title_legacy_story(
  p_player_id bigint,p_title_date date,p_tournament_name text,p_level text
)
returns jsonb
language plpgsql
security invoker
set search_path to ''
as $function$
declare
  v_event_key text; v_name text; v_country text; v_slams bigint:=0; v_club bigint:=0;
  v_event_titles bigint:=0; v_catalog_code text; v_catalog public.record_catalog%rowtype; v_story_count int:=0;
begin
  if p_title_date<=date '2025-12-01' then return jsonb_build_object('ok',true,'published',0,'reason','baseline_cutoff'); end if;
  select name,country into v_name,v_country from public.players where id=p_player_id;
  if v_name is null then return jsonb_build_object('ok',false,'reason','player_not_found'); end if;
  v_event_key:=public.cb_record_event_key(p_tournament_name);

  if public.court_boss_publish_legacy_rank_story(p_player_id,p_title_date,'son titre à '||coalesce(p_tournament_name,'un tournoi majeur')) then
    v_story_count:=v_story_count+1;
  end if;

  if v_event_key in ('australian_open','roland_garros','wimbledon','us_open') then
    select coalesce(grand_slams,0) into v_slams
    from public.court_boss_legacy_leaderboard(p_title_date) where player_id=p_player_id;

    if v_slams in (1,5,10,15,20,24,25,30) then
      select count(*) into v_club from public.court_boss_legacy_leaderboard(p_title_date) where grand_slams>=v_slams;
      if public.court_boss_publish_world_story(
        'slam_milestone:'||p_player_id||':'||v_slams,p_title_date,p_player_id,'slam_milestone',
        v_name||' atteint '||v_slams||' titre'||case when v_slams>1 then 's' else '' end
          ||' du Grand Chelem à '||coalesce(p_tournament_name,'un Majeur')
          ||case when v_slams>=5 then ' et rejoint le club des '||v_club||' joueurs à ce niveau dans l’histoire Court Boss' else '' end||'.',
        jsonb_build_object('grand_slams',v_slams,'club_size',v_club,'tournament',p_tournament_name)
      ) then v_story_count:=v_story_count+1; end if;
    end if;

    if v_slams>=24 and not exists(
      select 1 from public.record_occurrences
      where record_code='grand_slam_titles_career' and player_id=p_player_id and coalesce(value,0)>=v_slams
    ) then
      insert into public.record_occurrences(record_code,player_id,player_name,country,season,achieved_on,value,label,source_type,source_label,source_url,metadata)
      values('grand_slam_titles_career',p_player_id,v_name,v_country,extract(year from p_title_date)::int,p_title_date,
        v_slams,v_slams||' Majeurs','career','Court Boss · Legacy news v1','',jsonb_build_object('tournament',p_tournament_name));
    end if;

    v_catalog_code:=case v_event_key
      when 'australian_open' then 'major_event_ao'
      when 'roland_garros' then 'major_event_rg'
      when 'wimbledon' then 'major_event_wimbledon'
      when 'us_open' then 'major_event_us_open_open_era' else null end;

    if v_catalog_code is not null then
      select * into v_catalog from public.record_catalog where code=v_catalog_code;
      select count(*) into v_event_titles
      from public.player_titles pt
      where pt.player_id=p_player_id and pt.event_type='singles' and pt.title_date<=p_title_date
        and public.cb_record_event_key(pt.tournament_name)=v_event_key;
      if v_catalog.code is not null and v_catalog.baseline_value is not null and v_event_titles>=v_catalog.baseline_value
        and not exists(select 1 from public.record_occurrences
          where record_code=v_catalog_code and player_id=p_player_id and coalesce(value,0)>=v_event_titles)
      then
        insert into public.record_occurrences(record_code,player_id,player_name,country,season,achieved_on,value,label,source_type,source_label,source_url,metadata)
        values(v_catalog_code,p_player_id,v_name,v_country,extract(year from p_title_date)::int,p_title_date,
          v_event_titles,v_event_titles||' titres · '||p_tournament_name,'career','Court Boss · Legacy news v1','',
          jsonb_build_object('tournament',p_tournament_name));
      end if;
    end if;
  end if;

  if coalesce(p_level,'') ilike '%ATP Finals%' or lower(coalesce(p_tournament_name,'')) like '%atp finals%'
     or lower(coalesce(p_tournament_name,'')) like '%tour finals%' then
    select count(*) into v_event_titles
    from public.player_titles pt
    where pt.player_id=p_player_id and pt.event_type='singles' and pt.title_date<=p_title_date
      and (coalesce(pt.level,'') ilike '%ATP Finals%'
        or lower(coalesce(pt.tournament_name,'')) like '%atp finals%'
        or lower(coalesce(pt.tournament_name,'')) like '%tour finals%'
        or lower(coalesce(pt.tournament_name,'')) like '%masters cup%');
    if v_event_titles>=7 and not exists(
      select 1 from public.record_occurrences where record_code='atp_finals_titles_career'
        and player_id=p_player_id and coalesce(value,0)>=v_event_titles
    ) then
      insert into public.record_occurrences(record_code,player_id,player_name,country,season,achieved_on,value,label,source_type,source_label,source_url,metadata)
      values('atp_finals_titles_career',p_player_id,v_name,v_country,extract(year from p_title_date)::int,p_title_date,
        v_event_titles,v_event_titles||' titres ATP Finals','career','Court Boss · Legacy news v1','',
        jsonb_build_object('tournament',p_tournament_name));
    end if;
  end if;

  return jsonb_build_object('ok',true,'published',v_story_count,'player_id',p_player_id,'date',p_title_date);
end;
$function$;

