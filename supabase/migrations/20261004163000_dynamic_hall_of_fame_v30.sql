-- Court Boss Hall of Fame V30
-- Dynamic retirement ceremonies, five-year eligibility, three-year ballot,
-- 75% election threshold, annual Newport classes, speeches and Legacy comparison.

create table if not exists public.court_boss_hof_profiles (
  player_id bigint primary key references public.players(id) on delete cascade,
  retired_date date not null,
  eligibility_year integer not null,
  status text not null default 'waiting' check(status in ('waiting','eligible','ballot','elected','inducted','expired','not_nominated')),
  first_nomination_year integer,
  ballots_count integer not null default 0,
  last_ballot_year integer,
  last_vote_pct numeric,
  peak_vote_pct numeric,
  hof_score bigint not null default 0,
  induction_year integer,
  induction_date date,
  class_number integer,
  legacy_rank_at_induction bigint,
  legacy_score_at_induction bigint,
  compared_to_player_id bigint references public.players(id) on delete set null,
  compared_to_player_name text,
  compared_to_rank bigint,
  retirement_ceremony_on date,
  retirement_speech text,
  induction_speech text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.court_boss_hof_ballots (
  id bigint generated by default as identity primary key,
  ballot_year integer not null,
  player_id bigint not null references public.players(id) on delete cascade,
  ballot_number integer not null check(ballot_number between 1 and 3),
  nomination_score bigint not null default 0,
  official_vote_pct numeric not null default 0,
  fan_rank integer,
  fan_bonus_pct numeric not null default 0,
  final_vote_pct numeric not null default 0,
  result text not null default 'nominated' check(result in ('nominated','elected','failed','final_ballot_failed')),
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(ballot_year,player_id)
);

create table if not exists public.court_boss_hof_classes (
  induction_year integer primary key,
  class_number integer not null,
  ballot_opened_on date,
  announced_on date,
  induction_date date not null,
  status text not null default 'voting' check(status in ('voting','elected','inducted','empty')),
  nominee_count integer not null default 0,
  elected_count integer not null default 0,
  inducted_count integer not null default 0,
  ceremony_title text,
  ceremony_location text not null default 'Newport, Rhode Island',
  summary text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.court_boss_retirement_ceremonies (
  player_id bigint primary key references public.players(id) on delete cascade,
  retirement_date date not null,
  ceremony_date date not null,
  player_name text not null,
  country text,
  legacy_rank bigint,
  legacy_score bigint,
  titles bigint not null default 0,
  grand_slams bigint not null default 0,
  masters bigint not null default 0,
  tour_finals bigint not null default 0,
  wins bigint not null default 0,
  weeks_no1 bigint not null default 0,
  eligibility_year integer not null,
  speech text not null,
  world_news_published boolean not null default false,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.court_boss_hof_profiles enable row level security;
alter table public.court_boss_hof_ballots enable row level security;
alter table public.court_boss_hof_classes enable row level security;
alter table public.court_boss_retirement_ceremonies enable row level security;

revoke all on public.court_boss_hof_profiles from public,anon,authenticated;
revoke all on public.court_boss_hof_ballots from public,anon,authenticated;
revoke all on public.court_boss_hof_classes from public,anon,authenticated;
revoke all on public.court_boss_retirement_ceremonies from public,anon,authenticated;

grant select,insert,update,delete on public.court_boss_hof_profiles to service_role;
grant select,insert,update,delete on public.court_boss_hof_ballots to service_role;
grant select,insert,update,delete on public.court_boss_hof_classes to service_role;
grant select,insert,update,delete on public.court_boss_retirement_ceremonies to service_role;
