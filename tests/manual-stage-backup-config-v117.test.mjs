import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync, readFileSync, rmSync, writeFileSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {spawnSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';

const helper = fileURLToPath(new URL('../scripts/cb-configure-local-pg17.py', import.meta.url));
const workflow = readFileSync(new URL('../.github/workflows/court-boss-stage-encrypted-backup.yml', import.meta.url), 'utf8');

test('workflow uses verified config helper instead of quoted sed/grep', () => {
  assert.match(workflow, /python3 "\$GITHUB_WORKSPACE\/scripts\/cb-configure-local-pg17\.py" supabase\/config\.toml/);
  assert.doesNotMatch(workflow, /sed -i 's\/\^major_version/);
  assert.match(workflow, /supabase db start/);
  assert.match(workflow, /github\.ref == 'refs\/heads\/court-boss-live'/);
});

for (const [name, setting] of [
  ['integer 15 generated by Supabase CLI', 'major_version = 15'],
  ['legacy quoted 15', 'major_version = "15"'],
  ['existing integer 17', 'major_version = 17'],
  ['integer 15 with comment', 'major_version = 15 # default'],
]) {
  test('config helper handles ' + name, () => {
    const dir = mkdtempSync(join(tmpdir(), 'cb-pg17-fixture-'));
    try {
      const config = join(dir, 'config.toml');
      writeFileSync(config, '[db]\nport = 54322\n' + setting + '\n[auth]\nenabled = true\n');
      const result = spawnSync('python3', [helper, config], {encoding: 'utf8'});
      assert.equal(result.status, 0, result.stderr);
      assert.match(result.stdout, /Verified local PostgreSQL major version: 17/);
      const contents = readFileSync(config, 'utf8');
      assert.match(contents, /^major_version = 17(?:\s*#.*)?$/m);
      assert.doesNotMatch(contents, /major_version = "17"/);
      assert.match(contents, /\[auth\]\nenabled = true/);
    } finally {
      rmSync(dir, {recursive: true, force: true});
    }
  });
}

test('config helper refuses missing version without rewriting file', () => {
  const dir = mkdtempSync(join(tmpdir(), 'cb-pg17-missing-'));
  try {
    const config = join(dir, 'config.toml');
    const original = '[db]\nport = 54322\n';
    writeFileSync(config, original);
    const result = spawnSync('python3', [helper, config], {encoding: 'utf8'});
    assert.notEqual(result.status, 0);
    assert.match(result.stderr, /Expected exactly one major_version setting/);
    assert.equal(readFileSync(config, 'utf8'), original);
  } finally {
    rmSync(dir, {recursive: true, force: true});
  }
});
